use proc_macro::TokenStream;
use proc_macro_crate::{FoundCrate, crate_name};
use proc_macro2::Span;
use quote::{format_ident, quote};
use syn::{ImplItem, ItemImpl, LitInt, LitStr, Token, parse::Parse, parse::ParseStream};

struct Metadata {
    version: u64,
    name: LitStr,
    description: LitStr,
}

impl Parse for Metadata {
    fn parse(input: ParseStream<'_>) -> syn::Result<Self> {
        let mut version = None;
        let mut name = None;
        let mut description = None;
        while !input.is_empty() {
            let key: syn::Ident = input.parse()?;
            input.parse::<Token![=]>()?;
            match key.to_string().as_str() {
                "version" => {
                    if version.is_some() {
                        return Err(syn::Error::new(key.span(), "duplicate `version` parameter"));
                    }
                    let literal: LitInt = input.parse()?;
                    let value = literal.base10_parse::<u64>()?;
                    if value == 0 {
                        return Err(syn::Error::new(
                            literal.span(),
                            "`version` must be at least 1",
                        ));
                    }
                    version = Some(value);
                }
                "name" => {
                    if name.is_some() {
                        return Err(syn::Error::new(key.span(), "duplicate `name` parameter"));
                    }
                    name = Some(input.parse::<LitStr>()?);
                }
                "description" => {
                    if description.is_some() {
                        return Err(syn::Error::new(
                            key.span(),
                            "duplicate `description` parameter",
                        ));
                    }
                    description = Some(input.parse::<LitStr>()?);
                }
                _ => {
                    return Err(syn::Error::new(
                        key.span(),
                        "unknown migration parameter; expected `version`, `name`, or `description`",
                    ));
                }
            }
            if !input.is_empty() {
                input.parse::<Token![,]>()?;
            }
        }
        Ok(Self {
            version: version.ok_or_else(|| input.error("missing `version` parameter"))?,
            name: name.ok_or_else(|| input.error("missing `name` parameter"))?,
            description: description.unwrap_or_else(|| LitStr::new("", Span::call_site())),
        })
    }
}

/// Supplies static metadata and async-trait support for a `Migration<H>` impl.
///
/// Requires `version = 1` (a positive u64 integer literal) and `name = "..."`.
/// `description` defaults to `""`. Do not also define metadata methods or
/// attach `async_trait`.
#[proc_macro_attribute]
pub fn migration(args: TokenStream, item: TokenStream) -> TokenStream {
    let metadata = syn::parse_macro_input!(args as Metadata);
    let implementation = syn::parse_macro_input!(item as ItemImpl);
    expand(metadata, implementation)
        .unwrap_or_else(syn::Error::into_compile_error)
        .into()
}

fn expand(
    metadata: Metadata,
    mut implementation: ItemImpl,
) -> syn::Result<proc_macro2::TokenStream> {
    if implementation.trait_.is_none() {
        return Err(syn::Error::new_spanned(
            &implementation.self_ty,
            "`migration` requires a Migration trait impl",
        ));
    }
    for attribute in &implementation.attrs {
        if attribute
            .path()
            .segments
            .last()
            .is_some_and(|segment| segment.ident == "async_trait")
        {
            return Err(syn::Error::new_spanned(
                attribute,
                "`migration` already applies async_trait; remove the extra attribute",
            ));
        }
    }
    for item in &implementation.items {
        if let ImplItem::Fn(method) = item {
            if matches!(
                method.sig.ident.to_string().as_str(),
                "version" | "name" | "description"
            ) {
                return Err(syn::Error::new_spanned(
                    &method.sig.ident,
                    "metadata methods are generated by `migration`; remove this method",
                ));
            }
        }
    }
    let Metadata {
        version,
        name,
        description,
    } = metadata;
    implementation.items.extend([
        syn::parse_quote! { fn version(&self) -> u64 { #version } },
        syn::parse_quote! { fn name(&self) -> &str { #name } },
        syn::parse_quote! { fn description(&self) -> &str { #description } },
    ]);
    let orbiv =
        match crate_name("orbiv").map_err(|error| syn::Error::new(Span::call_site(), error))? {
            FoundCrate::Itself => quote!(::orbiv),
            FoundCrate::Name(name) => {
                let ident = format_ident!("{}", name);
                quote!(::#ident)
            }
        };
    Ok(quote! {
        #[#orbiv::__private::async_trait]
        #implementation
    })
}
